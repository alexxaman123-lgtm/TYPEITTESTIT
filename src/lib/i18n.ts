type TranslationShape = {
  [Section in keyof typeof translations.en]: {
    [Key in keyof typeof translations.en[Section]]: string;
  };
};

// Compile-time guard: a new English key cannot silently fall back in another locale.
const completeTranslations: Record<Locale, TranslationShape> = translations;

type TranslationSection = keyof typeof translations.en;

export function tr(locale: Locale, section: TranslationSection, key: string): string {
  const localeTable = completeTranslations[locale];
  const value = (localeTable?.[section] as Record<string, string> | undefined)?.[key];
  const fallback = (translations.en[section] as Record<string, string> | undefined)?.[key];
  return value ?? fallback ?? key;
}
